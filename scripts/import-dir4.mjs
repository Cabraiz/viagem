// 4-direction atlas import (NEW-20261009-ORQ-sprites-4-direcoes), used by scripts/import-sprites.mjs --dir4 and the tests.
// All-or-nothing: every atlas of the batch is validated (and every overwrite refused) BEFORE any file is written, so a
// bad atlas never leaves a good one half-imported (an orphan .dir4.webp without its catalog entry).
import {readFile,writeFile,mkdir,stat,readdir} from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {validateDirectionalAtlas,approvedPivotX} from './sprite-atlas.mjs';

export const CATALOG='src/client/sprites/sprite-catalog.ts';
const exists=file=>stat(file).then(()=>true,()=>false);
export async function readCatalog(file=CATALOG){
  const text=await readFile(file,'utf8');
  return JSON.parse(text.slice(text.indexOf('=',text.indexOf('spriteCatalog'))+1).replace(/;\s*$/,''));
}
export const writeCatalog=(catalog,file=CATALOG)=>writeFile(file,`// Generated by scripts/import-sprites.mjs. Artwork remains a first-version candidate.\n/** Box of the drawn figure inside a 192 px cell, all cells together (alpha > 20). */\nexport interface FigureBox {left:number;top:number;right:number;bottom:number}\nexport const spriteCatalog:Record<string,{height:number;figure?:FigureBox;dir4?:{height:number;figure?:FigureBox}}>=${JSON.stringify(catalog,null,2)};\n`);

/**
 * Imports `<root>/<id>/atlas-4dir.png` or `<root>/<id>.dir4.png` for the given class ids. `lab` writes the TEST batch
 * to `outDir` and leaves the catalog alone. Throws (writing nothing) with every problem of every atlas.
 */
export async function importDirectional({root,ids,outDir='public/art/sprites',approvedDir='public/art/sprites',catalogFile=CATALOG,lab=false,replace=false}){
  const names=new Set(await readdir(root));
  const catalog=lab?undefined:await readCatalog(catalogFile);
  const found=[],problems=[];
  for(const id of ids){
    let source;
    for(const candidate of [path.join(root,id,'atlas-4dir.png'),path.join(root,`${id}.dir4.png`)])if(await exists(candidate)){source=candidate;break;}
    if(!source)continue;
    names.delete(id);names.delete(`${id}.dir4.png`);
    if(catalog&&!catalog[id]){problems.push(`${id}: a classe não tem folha aprovada; importe a folha de uma direção primeiro`);continue;}
    const output=path.join(outDir,`${id}.dir4.webp`);
    if(!lab&&!replace&&await exists(output)){problems.push(`${id}: ${output} já existe; use --replace para trocar arte de 4 direções aprovada`);continue;}
    try{
      const pivotX=await approvedPivotX(path.join(approvedDir,`${id}.webp`));
      found.push({id,source,output,pivotX,...await validateDirectionalAtlas(source,id,{pivotX})});
    }catch(e){problems.push(e.message);}
  }
  const ignored=[...names].filter(n=>!n.startsWith('.'));
  if(problems.length)throw new Error(`Nada foi gravado. Problemas:\n${problems.join('\n')}`);
  if(!found.length)throw new Error('Nenhum atlas de 4 direções encontrado (<pasta>/<id>/atlas-4dir.png ou <pasta>/<id>.dir4.png).');
  await mkdir(outDir,{recursive:true});
  const report=[];
  for(const f of found){
    await sharp(f.source).webp({lossless:true,effort:6}).toFile(f.output);
    if(catalog)catalog[f.id]={...catalog[f.id],dir4:{height:f.height,figure:f.figure}};
    report.push({id:f.id,source:f.source,output:f.output,bytes:(await stat(f.output)).size,frames:72,lab,height:f.height,pivotX:f.pivotX,figure:f.figure,facings:f.facings});
  }
  if(catalog)await writeCatalog(catalog,catalogFile);
  return {report,ignored};
}
