// Atlas of the city's ground albedo (card NEW-20261014-ORQ-chao-albedo-cidade, design/proximos/09-CHAO-ALBEDO.md):
// the 6 seamless 1024² PNGs the user delivered (viagem-board/arte-entrada/chao/<material>-albedo.png) → one WebP atlas
// of 4×2 slots (power of two, so the GPU can mipmap it): each material resized to TILE − 2·PAD px and grown back to
// TILE by mirroring its edges (the shader reads it with mirrored UVs, so a coarse mip level never bleeds the next
// material in). Also writes src/client/render/city/relevo/albedo-meta.ts: slot order, the atlas size and each
// material's mean colour (the shader divides by it: the albedo brings detail, the palette keeps the colour).
//   node scripts/chao-albedo.mjs [--entrada <dir>] [--tile 512] [--qualidade 80] [--saida public/art/lite/chao/cidade-albedo.webp]
import sharp from 'sharp';
import {mkdirSync,writeFileSync,statSync} from 'node:fs';
import {dirname,join} from 'node:path';

const args=process.argv.slice(2),opt=(n,f)=>{const i=args.indexOf(`--${n}`);return i>=0?args[i+1]:f;};
const entrada=opt('entrada','D:/Gits/viagem-board/arte-entrada/chao');
const TILE=Number(opt('tile','512')),PAD=Math.round(TILE/32),Q=Number(opt('qualidade','80'));
const saida=opt('saida','public/art/lite/chao/cidade-albedo.webp');
/** Slot order (the shader's ALBEDO_* constants follow it). */
export const SLOTS=['neve','neve-pisada','calcada','gelo','terra','asfalto'];
const COLS=4,ROWS=2;

const tiles=[],means=[];
for(const name of SLOTS){
  const inner=TILE-2*PAD;
  const img=sharp(join(entrada,`${name}-albedo.png`)).removeAlpha().resize(inner,inner,{kernel:'lanczos3'});
  const {data,info}=await img.clone().raw().toBuffer({resolveWithObject:true});
  const sum=[0,0,0];for(let i=0;i<data.length;i+=info.channels)for(let c=0;c<3;c++)sum[c]+=data[i+c];
  const n=data.length/info.channels;means.push(sum.map(s=>+(s/n/255).toFixed(4)));
  tiles.push(await img.extend({top:PAD,bottom:PAD,left:PAD,right:PAD,extendWith:'mirror'}).png().toBuffer());
}
mkdirSync(dirname(saida),{recursive:true});
await sharp({create:{width:COLS*TILE,height:ROWS*TILE,channels:3,background:'#808080'}})
  .composite(tiles.map((input,i)=>({input,left:(i%COLS)*TILE,top:Math.floor(i/COLS)*TILE})))
  .webp({quality:Q,effort:6}).toFile(saida);

const meta=`// Generated by scripts/chao-albedo.mjs from viagem-board/arte-entrada/chao (do not edit by hand).
/** The ground albedo atlas (card NEW-20261014-ORQ-chao-albedo-cidade): its URL, layout and each slot's mean colour. */
export const ALBEDO_URL='/${saida.replace(/^public\//,'')}';
export const ALBEDO_SLOTS=${JSON.stringify(SLOTS)} as const;
export const ALBEDO_GRID={cols:${COLS},rows:${ROWS},tile:${TILE},pad:${PAD}} as const;
/** Mean colour (0..1 RGB) of each slot's material, in ALBEDO_SLOTS order. */
export const ALBEDO_MEANS:readonly (readonly [number,number,number])[]=${JSON.stringify(means)};
`;
writeFileSync('src/client/render/city/relevo/albedo-meta.ts',meta);
console.log(`${saida}: ${COLS*TILE}×${ROWS*TILE}, ${(statSync(saida).size/1024).toFixed(0)} KB; médias ${means.map((m,i)=>`${SLOTS[i]} ${m.join('/')}`).join(' · ')}`);
