// The roster ids that have imported art (arte-do-roster-no-render, ROSTER_ONLY_WITH_ART): the sim never reads the art
// index, so the importer writes this list next to it as rules data, src/rules/enemy-art-ids.ts. The importer calls
// writeEnemyArtIds after every index write (scripts/import-art-v2.mjs); by hand, after editing the index:
//
//   node scripts/art-v2/enemy-art-ids.mjs
//
// tests/rules/enemy-art-ids.test.ts keeps the two in sync.
import {access,readFile,writeFile,rename} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {INDEX_FILE} from './spec.mjs';

export const ART_IDS_FILE='src/rules/enemy-art-ids.ts';
/** The ids of the index's `inimigos` group, sorted (an index without the group: none). */
export const enemyArtIds=index=>Object.keys(index?.groups?.inimigos?.pieces??{}).sort();
/** The TypeScript module for `ids` (same bytes for the same ids). */
export function enemyArtIdsSource(ids){
  return `// GENERATED by scripts/art-v2/enemy-art-ids.mjs from ${INDEX_FILE} (group inimigos). Do not edit by hand: the
// importer rewrites it with the index, and \`node scripts/art-v2/enemy-art-ids.mjs\` regenerates it.
/**
 * Roster ids with imported art (arte-do-roster-no-render): what the rotation draws from while ROSTER_ONLY_WITH_ART is on
 * (rules/enemy-rotation.ts). The sim never reads the art index; tests/rules/enemy-art-ids.test.ts pins the two equal.
 */
export const ENEMY_ART_IDS:readonly string[]=Object.freeze([
${ids.map(id=>`  ${JSON.stringify(id).replace(/"/g,"'")},`).join('\n')}
]);
`;
}
/**
 * Rewrites ART_IDS_FILE under `outRoot` from the index there (atomically); returns the file path. A root without the
 * rules folder (the importer's tests write to a scratch root) or without an index writes nothing (undefined).
 */
export async function writeEnemyArtIds({outRoot}){
  try{await access(path.join(outRoot,...path.dirname(ART_IDS_FILE).split('/')));}catch{return undefined;}
  let index;try{index=JSON.parse(await readFile(path.join(outRoot,...INDEX_FILE.split('/')),'utf8'));}catch{return undefined;}
  const file=path.join(outRoot,...ART_IDS_FILE.split('/')),tmp=`${file}.tmp`;
  await writeFile(tmp,enemyArtIdsSource(enemyArtIds(index)));await rename(tmp,file);
  return file;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..','..');
  console.log(await writeEnemyArtIds({outRoot:root}));
}
