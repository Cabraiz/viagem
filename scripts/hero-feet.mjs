#!/usr/bin/env node
/**
 * Card NEW-20261021-ORQ-passo-sem-deslizar: measures, offline, where each detailed hero clip (M16 walk/attack/idle,
 * R06 walk128/attack128/idle8) touches the ground and writes src/client/sprites/hero-feet-data.ts.
 * Per frame: the lowest opaque row (alpha > 128: the manifest's figure box counts the soft rim, ~3 px lower). Per clip: the median over its frames (a walk's planted foot keeps
 * that row in every frame, ±1 px), so the hero, its contact shadow and its silhouette meet on the same line in every
 * clip and direction (the class-wide median of before left the viciado's walk 3–4 px over the ground).
 * Keyed by the sheet's file name (it carries the sha12): a reimported sheet has no entry and the client falls back to
 * hero-feet.ts heroFeetY.
 *
 *   node scripts/hero-feet.mjs            # writes the table
 *   node scripts/hero-feet.mjs --check    # exits 1 if the table is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sharp=createRequire(path.join(ROOT,'package.json'))('sharp');
const MANIFEST=path.join(ROOT,'public/art/manifest.json');
const OUT=path.join(ROOT,'src/client/sprites/hero-feet-data.ts');
const HEAD=`// Generated by scripts/hero-feet.mjs (card NEW-20261021-ORQ-passo-sem-deslizar): do not edit.
/** Sheet file name → the feet row (96 px cell px from the top): where the clip's figure touches the ground. */
export const HERO_FEET:Readonly<Record<string,number>>=`;
const CELL=96,CLIP=/^(walk|attack|idle)(16|128)-[A-Z]+$|^idle8$/;
const median=a=>{const s=[...a].sort((x,y)=>x-y),m=s.length>>1;return s.length%2?s[m]:(s[m-1]+s[m])/2;};

const manifest=JSON.parse(fs.readFileSync(MANIFEST,'utf8'));
const pieces=manifest.groups.personagens.pieces??manifest.groups.personagens;
const table={};
for(const [id,piece] of Object.entries(pieces)){
  for(const [name,f] of Object.entries(piece.files??{})){
    if(!CLIP.test(name)||f.cell?.[0]!==CELL||f.cell?.[1]!==CELL||f.pages?.length!==1)continue;
    const page=f.pages[0];
    const {data,info}=await sharp(path.join(ROOT,'public/art/sprites',page.file)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const rows=[];
    for(let i=0;i<page.frameCount;i++){
      const c=i%page.columns,r=Math.floor(i/page.columns),a=(x,y)=>data[((r*CELL+y)*info.width+c*CELL+x)*4+3]>128;
      let bottom=-1;
      for(let y=CELL-1;y>=0&&bottom<0;y--)for(let x=0;x<CELL;x++)if(a(x,y)){bottom=y;break;}
      if(bottom>=0)rows.push(bottom+1);
    }
    if(!rows.length)continue;
    table[page.file]=median(rows);
  }
}
const sorted=Object.fromEntries(Object.entries(table).sort(([a],[b])=>a.localeCompare(b)));
const text=HEAD+'{\n'+Object.entries(sorted).map(([k,v])=>`${JSON.stringify(k)}:${v}`).join(',\n')+'\n};\n';
if(process.argv.includes('--check')){
  const stale=!fs.existsSync(OUT)||fs.readFileSync(OUT,'utf8')!==text;
  console.log(stale?'hero-feet-data.ts is stale: run node scripts/hero-feet.mjs':'hero-feet-data.ts is current');
  process.exit(stale?1:0);
}
fs.writeFileSync(OUT,text);
console.log(`${Object.keys(sorted).length} clips → ${path.relative(ROOT,OUT)}`);
