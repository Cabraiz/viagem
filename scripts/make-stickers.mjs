/** Checks a grid and returns its letters in a 24×24 box (null = empty), the art placed at PAD. */
export function place(name,grid){
  if(grid.length!==N)throw new Error(`${name}: ${grid.length} rows, expected ${N}`);
  const cells=Array.from({length:BOX},()=>Array(BOX).fill(null));
  grid.forEach((row,y)=>{
    if(row.length!==N)throw new Error(`${name}: row ${y} has ${row.length} letters, expected ${N}`);
    [...row].forEach((ch,x)=>{
      if(ch==='.')return;
      if(!PALETTE[ch])throw new Error(`${name}: unknown letter "${ch}" at ${x},${y}`);
      cells[y+PAD][x+PAD]=ch;
    });
  });
  return cells;
}
/** Outline (4-neighbourhood of the art), paper edge (8-neighbourhood of art + outline), hard shadow (paper, 1 px down). */
export function layers(cells){
  const at=(m,x,y)=>y>=0&&y<BOX&&x>=0&&x<BOX&&m[y][x];
  const art=cells.map(row=>row.map(c=>!!c));
  const grow=(m,diag)=>m.map((row,y)=>row.map((v,x)=>v||[[1,0],[-1,0],[0,1],[0,-1],...(diag?[[1,1],[1,-1],[-1,1],[-1,-1]]:[])].some(([dx,dy])=>at(m,x+dx,y+dy))));
  const lined=grow(art,false);
  const outline=lined.map((row,y)=>row.map((v,x)=>v&&!art[y][x]));
  const paper=grow(lined,true);
  return {art,outline,paper};
}
/** The rim shadow (see RAMPS): one step darker where the right or lower neighbour is empty. */
export function shade(cells){
  const step=new Map();for(const r of RAMPS)for(let i=0;i<r.length-1;i++)step.set(r[i],r[i+1]);
  return cells.map((row,y)=>row.map((c,x)=>{
    if(!c||!step.has(c))return c;
    const edge=!(row[x+1])||!(cells[y+1]?.[x]);
    return edge?step.get(c):c;
  }));
}
/** One path per color: each horizontal run of pixels is a rectangle (M x y h w v 1 h -w z). */
function runs(mask,dy=0){
  let d='';
  mask.forEach((row,y)=>{for(let x=0;x<row.length;){if(!row[x]){x++;continue;}let e=x;while(e<row.length&&row[e])e++;d+=`M${x} ${y+dy}h${e-x}v1h${x-e}z`;x=e;}});
  return d;
}
export function buildSprite(){
  const symbols=[];
  for(const [name,title,grid] of STICKERS){
    const cells=shade(place(name,grid)),{outline,paper}=layers(cells);
    const parts=[`<path class="px-sombra" d="${runs(paper,1)}"/>`,`<path class="px-borda" d="${runs(paper)}"/>`,`<path class="px-contorno" d="${runs(outline)}"/>`];
    for(const ch of Object.keys(PALETTE)){
      const mask=cells.map(row=>row.map(c=>c===ch));
      if(mask.some(row=>row.some(Boolean)))parts.push(`<path class="px-${PALETTE[ch]}" d="${runs(mask)}"/>`);
    }
    symbols.push(`<symbol id="a-${name}" viewBox="0 0 ${BOX} ${BOX}"><title>${title}</title>${parts.join('')}</symbol>`);
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
<!-- Adesivos de itens, prêmios e sons em pixel art (NEW-20261009-DSG-adesivos-itens). GERADO por scripts/make-stickers.mjs:
     não edite à mão. Cores só por classe (src/client/ui/icons.css, tokens --arte-*). -->
${symbols.join('\n')}
</svg>
`;
}

