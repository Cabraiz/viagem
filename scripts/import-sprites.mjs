// Sprite importer. Two modes:
//   node --experimental-strip-types scripts/import-sprites.mjs <batchDir>
//       the approved single-direction sheets (lote-N/<id>/), regenerates src/game/sprite-catalog.ts.
//   node --experimental-strip-types scripts/import-sprites.mjs --dir4 <dir> [--lab] [--replace]
//       4-direction atlases (<dir>/<id>/atlas-4dir.png or <dir>/<id>.dir4.png; format in docs/sprite-directions.md).
//       Adds public/art/sprites/<id>.dir4.webp and the class's `dir4` entry in the catalog. The approved <id>.webp is
//       never written; an existing <id>.dir4.webp is only replaced with --replace. --lab writes the TEST batch to
//       tests/fixtures/sprites-4dir/ instead and leaves the catalog alone.
import {readFile,writeFile,mkdir,stat,readdir} from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {classes} from '../src/classes.ts';
import {validateSingleSheet,validateDirectionalAtlas} from './sprite-atlas.mjs';

const CATALOG='src/game/sprite-catalog.ts';
const exists=file=>stat(file).then(()=>true,()=>false);
const writeCatalog=catalog=>writeFile(CATALOG,`// Generated by scripts/import-sprites.mjs. Artwork remains a first-version candidate.\nexport const spriteCatalog:Record<string,{height:number;dir4?:{height:number}}>=${JSON.stringify(catalog,null,2)};\n`);
async function readCatalog(){
  const text=await readFile(CATALOG,'utf8');
  return JSON.parse(text.slice(text.indexOf('=',text.indexOf('spriteCatalog'))+1).replace(/;\s*$/,''));
}
await mkdir('artifacts',{recursive:true});
const args=process.argv.slice(2);

if(args[0]==='--dir4'){
  const root=args[1],lab=args.includes('--lab'),replace=args.includes('--replace');
  if(!root)throw new Error('Pass the 4-direction batch directory.');
  const outDir=lab?'tests/fixtures/sprites-4dir':'public/art/sprites';
  await mkdir(outDir,{recursive:true});
  const names=new Set(await readdir(root));
  const catalog=lab?undefined:await readCatalog();
  const report=[];
  for(const hero of classes){
    let source;
    for(const candidate of [path.join(root,hero.id,'atlas-4dir.png'),path.join(root,`${hero.id}.dir4.png`)])if(await exists(candidate)){source=candidate;break;}
    if(!source)continue;
    names.delete(hero.id);names.delete(`${hero.id}.dir4.png`);
    if(catalog&&!catalog[hero.id])throw new Error(`No approved sheet for ${hero.id}: import the single-direction sheet first.`);
    const result=await validateDirectionalAtlas(source,hero.id);
    const output=path.join(outDir,`${hero.id}.dir4.webp`);
    if(!lab&&!replace&&await exists(output))throw new Error(`${output} already exists: pass --replace to swap approved 4-direction art.`);
    await sharp(source).webp({lossless:true,effort:6}).toFile(output);
    if(catalog)catalog[hero.id]={...catalog[hero.id],dir4:{height:result.height}};
    report.push({id:hero.id,source,output,bytes:(await stat(output)).size,frames:72,lab,...result});
  }
  const unknown=[...names].filter(n=>!n.startsWith('.'));
  if(unknown.length)console.warn(`Ignored (not a class id): ${unknown.join(', ')}`);
  if(!report.length)throw new Error('No 4-direction atlas found.');
  if(catalog)await writeCatalog(catalog);
  await writeFile(`artifacts/sprite-import-dir4${lab?'-lab':''}-report.json`,JSON.stringify(report,null,2));
  console.log(JSON.stringify({classes:report.length,lab,bytes:report.reduce((n,r)=>n+r.bytes,0),heights:Object.fromEntries(report.map(r=>[r.id,r.height]))}));
}else{
  const root=args[0];
  if(!root)throw new Error('Pass the sprite batch directory.');
  await mkdir('public/art/sprites',{recursive:true});
  const previous=await readCatalog().catch(()=>({}));
  const report=[],catalog={};
  for(const [i,hero] of classes.entries()){
    const batch=path.join(root,`lote-${Math.floor(i/6)+1}`),dir=path.join(batch,hero.id);
    const status=JSON.parse(await readFile(path.join(dir,'status.json'),'utf8'));
    let source;
    try{const meta=JSON.parse(await readFile(path.join(dir,'atlas.json'),'utf8'));source=path.join(dir,meta.image);}catch{
      const file=status.files.atlas;
      for(const candidate of [path.join(dir,file),path.join(batch,file)])if(await exists(candidate)){source=candidate;break;}
    }
    if(!source)throw new Error(`Missing atlas: ${hero.id}`);
    const {height}=await validateSingleSheet(source,hero.id);
    const output=`public/art/sprites/${hero.id}.webp`;
    await sharp(source).webp({lossless:true,effort:6}).toFile(output);
    catalog[hero.id]={height};
    // Re-importing the single sheets keeps the 4-direction entries whose atlas is in place.
    if(previous[hero.id]?.dir4&&await exists(`public/art/sprites/${hero.id}.dir4.webp`))catalog[hero.id].dir4=previous[hero.id].dir4;
    report.push({id:hero.id,source,output,bytes:(await stat(output)).size,frames:18,artStatus:'candidate',issues:status.remainingIssues??status.remainingProblems??status.issues??[]});
  }
  await writeCatalog(catalog);
  await writeFile('artifacts/sprite-import-report.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify({classes:report.length,frames:report.length*18,bytes:report.reduce((n,r)=>n+r.bytes,0)}));
}
