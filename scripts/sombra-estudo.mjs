#!/usr/bin/env node
// Shadow study (BUG-20261017-ORQ-sombra-longe-personagem-pequeno): per enemy, from the alpha of its imported art
// (public/art/enemies/manifest.json), where the feet really are and how wide its footing is, so the contact shadow sits
// on the feet and is as wide as what touches the ground (not the procedural kind's width).
//   node scripts/sombra-estudo.mjs            writes src/client/art/enemy-feet.ts and evidence/BUG-sombra/sombra-estudo.md
//   node scripts/sombra-estudo.mjs --check    exits 1 when the table is stale (the art changed)
// Per body file (no layers: elite/…, costume/…), every cell of every page: the feet row = lowest row with alpha > 20;
// the footing = opaque width in the band FOOT_BAND × figure height above the feet. The loop the game shows most
// (walk, else fly, else idle) gives the table's numbers: medians over its cells, as fractions of the cell.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const MANIFEST=path.join(ROOT,'public/art/enemies/manifest.json');
const OUT_TS=path.join(ROOT,'src/client/art/enemy-feet.ts');
const OUT_MD=path.join(ROOT,'evidence/BUG-sombra/sombra-estudo.md');
const ALPHA=20,FOOT_BAND=.12,DEVIATION_PX=4;
const LOOPS=['walk','fly','idle'];

const median=a=>{const s=[...a].sort((x,y)=>x-y);return s.length?s[s.length>>1]:0;};
const r3=v=>Math.round(v*1000)/1000;

/** Per cell of a sheet: {feet, top, foot} in cell px (feet = 1 + the lowest opaque row), or null for an empty cell. */
async function cells(file,page,cell){
  const {data,info}=await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const [cw,ch]=cell,out=[];
  for(let r=0;r<page.rows;r++)for(let c=0;c<page.columns;c++){
    if(out.length>=page.frameCount)break;
    let feet=-1,top=-1;
    const rowWidth=new Array(ch).fill(0),rowMin=new Array(ch).fill(cw),rowMax=new Array(ch).fill(-1);
    for(let y=0;y<ch;y++){
      const py=r*ch+y;if(py>=info.height)break;
      for(let x=0;x<cw;x++){
        const px=c*cw+x;if(px>=info.width)break;
        if(data[(py*info.width+px)*4+3]>ALPHA){if(top<0)top=y;feet=y;if(x<rowMin[y])rowMin[y]=x;if(x>rowMax[y])rowMax[y]=x;}
      }
      if(rowMax[y]>=0)rowWidth[y]=rowMax[y]-rowMin[y]+1;
    }
    if(feet<0){out.push(null);continue;}
    const band=Math.max(1,Math.round((feet-top+1)*FOOT_BAND));
    let lo=cw,hi=-1;
    for(let y=feet-band+1;y<=feet;y++)if(rowMax[y]>=0){lo=Math.min(lo,rowMin[y]);hi=Math.max(hi,rowMax[y]);}
    out.push({feet:feet+1,top,foot:hi>=lo?hi-lo+1:0});
  }
  return out;
}

async function study(){
  const manifest=JSON.parse(fs.readFileSync(MANIFEST,'utf8'));
  const table={},rows=[],sleep={};
  for(const [id,piece] of Object.entries(manifest.pieces).sort(([a],[b])=>a.localeCompare(b))){
    for(const [name,f] of Object.entries(piece.files)){
      if(name.includes('/'))continue;
      const all=[];
      for(const page of f.pages){
        const file=path.join(ROOT,'public/art/enemies',page.file);
        if(fs.existsSync(file))all.push(...(await cells(file,page,f.cell)).filter(Boolean));
      }
      if(!all.length)continue;
      const [cw,ch]=f.cell,anchor=(f.anchor?.[1]??.88)*ch;
      const feetMax=Math.max(...all.map(c=>c.feet)),figure=median(all.map(c=>c.feet-c.top));
      rows.push({id,name,ch,anchor:Math.round(anchor),feet:feetMax,gap:Math.round(anchor-feetMax),figure,fly:name==='fly'});
      if(name==='sleep'){sleep[id]=r3(median(all.map(c=>c.foot))/cw);continue;}
      if(!table[id]&&LOOPS.includes(name))table[id]={from:name,feetY:r3(median(all.map(c=>c.feet))/ch),footW:r3(median(all.map(c=>c.foot))/cw),figureH:r3(figure/ch)};
      else if(table[id]&&LOOPS.indexOf(name)>=0&&LOOPS.indexOf(name)<LOOPS.indexOf(table[id].from))
        table[id]={from:name,feetY:r3(median(all.map(c=>c.feet))/ch),footW:r3(median(all.map(c=>c.foot))/cw),figureH:r3(figure/ch)};
    }
  }
  for(const [id,t] of Object.entries(table))if(sleep[id]!==undefined)t.sleepW=sleep[id];
  return {table,rows};
}

function render({table,rows}){
  const ts=`// Generated by scripts/sombra-estudo.mjs from public/art/enemies/manifest.json: do not edit by hand.
// Per enemy art id, its most shown loop (walk, else fly, else idle), medians over its cells, as fractions of the cell:
// feetY = where the feet touch the ground (lowest opaque row), footW = the footing's width (opaque width in the lowest
// ${FOOT_BAND*100} % of the figure), figureH = the figure's height; sleepW = the footing of its \`sleep\` loop (lying down).
// The contact shadow sits at the anchor and is that footing wide.
export interface EnemyFeet {from:'walk'|'fly'|'idle';feetY:number;footW:number;figureH:number;sleepW?:number}
export const ENEMY_FEET:Readonly<Record<string,EnemyFeet>>=Object.freeze({
${Object.entries(table).map(([id,t])=>`  '${id}':{from:'${t.from}',feetY:${t.feetY},footW:${t.footW},figureH:${t.figureH}${t.sleepW!==undefined?`,sleepW:${t.sleepW}`:''}},`).join('\n')}
});
`;
  const off=rows.filter(r=>Math.abs(r.gap)>DEVIATION_PX).sort((a,b)=>Math.abs(b.gap)-Math.abs(a.gap));
  const md=`# Estudo da sombra por bicho (gerado por scripts/sombra-estudo.mjs)

Para cada folha de corpo de cada inimigo (sem as camadas elite/fantasia), em todas as células: **pé** = linha opaca mais
baixa (alfa > ${ALPHA}); **âncora** = anchor[1] × altura da célula (onde o jogo põe o ponto do chão e a sombra).
**Desvio** = âncora − pé, em px da célula: positivo = o pé fica ACIMA da âncora (o bicho flutua sobre a sombra).
Os voadores (animação \`fly\`) flutuam de propósito.

- Folhas medidas: ${rows.length}. Com |desvio| > ${DEVIATION_PX} px: **${off.length}** (${off.filter(r=>r.fly).length} delas de voo).

| bicho | animação | célula | âncora | pé | desvio (px) | figura (px) |
|---|---|---|---|---|---|---|
${off.map(r=>`| ${r.id} | ${r.name}${r.fly?' (voo)':''} | ${r.ch} | ${r.anchor} | ${r.feet} | ${r.gap>0?'+':''}${r.gap} | ${r.figure} |`).join('\n')}

## Apoio por bicho (a elipse de contato)

| bicho | laço | pé (fração) | apoio (fração da largura) | apoio dormindo | figura (fração da altura) |
|---|---|---|---|---|---|
${Object.entries(table).map(([id,t])=>`| ${id} | ${t.from} | ${t.feetY} | ${t.footW} | ${t.sleepW??'—'} | ${t.figureH} |`).join('\n')}
`;
  return {ts,md};
}

const {ts,md}=render(await study());
if(process.argv.includes('--check')){
  const now=fs.existsSync(OUT_TS)?fs.readFileSync(OUT_TS,'utf8'):'';
  if(now!==ts){console.error('src/client/art/enemy-feet.ts is stale: run node scripts/sombra-estudo.mjs');process.exit(1);}
  console.log('enemy-feet.ts up to date');
}else{
  fs.writeFileSync(OUT_TS,ts);fs.writeFileSync(OUT_MD,md);
  console.log(`wrote ${path.relative(ROOT,OUT_TS)} and ${path.relative(ROOT,OUT_MD)}`);
}
