import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import sharp from 'sharp';

// Technical atlas packing only: preserve generated artwork and alpha, align feet.
const root=path.resolve('artifacts/trees-v2');
const read=async file=>JSON.parse((await fs.readFile(file,'utf8')).replace(/^\uFEFF/,''));
const base=await read(path.join(root,'generation.json'));
const extra=await read(path.join(root,'generation-extra.json'));
const records=[...new Map([...base,...extra].map(t=>[t.id,t])).values()];
const original=(await read(path.join(root,'original-atlases/manifest.json'))).trees;
assert.equal(records.length,40,'Generate all forty trees before replacing runtime assets');
const staging=path.join(root,'packed');await fs.mkdir(staging,{recursive:true});
const catalog=[],report=[];
function bounds(data,width,height){
  let left=width,right=-1,top=height,bottom=-1,count=0;
  for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(data[(y*width+x)*4+3]>16){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);count++;}
  assert.ok(count>400&&count<width*height*.85,'Missing tree cutout');
  return {left,right,top,bottom,count};
}
for(const tree of original){
  const source=records.find(t=>t.id===tree.id);assert.ok(source,tree.id);
  const meta=await sharp(source.path).metadata();assert.ok(meta.hasAlpha,tree.id);assert.equal(meta.width,1024);assert.equal(meta.height,1536);
  const inputs=[];
  for(let i=0;i<4;i++){
    const data=await sharp(source.path).extract({left:i%2*512,top:Math.floor(i/2)*768,width:512,height:768}).ensureAlpha().raw().toBuffer();
    const b=bounds(data,512,768);
    let sum=0,n=0;
    // Root-footprint centroid anchors leaning trees independently of their crown.
    for(let y=b.bottom-40;y<=b.bottom;y++)for(let x=b.left;x<=b.right;x++)if(data[(y*512+x)*4+3]>128){sum+=x;n++;}
    const anchor=n?sum/n:256;
    inputs.push({data,b,anchor});
  }
  const scale=Math.min(...inputs.map(({b,anchor})=>Math.min(340/(b.bottom-b.top+1),116/Math.max(anchor-b.left,b.right-anchor))));
  const frames=[],composite=[];
  for(let i=0;i<4;i++){
    const {data,b,anchor}=inputs[i];
    const left=Math.max(0,b.left-2),top=Math.max(0,b.top-2),width=Math.min(512,b.right+3)-left,height=Math.min(768,b.bottom+3)-top;
    const w=Math.round(width*scale),h=Math.round(height*scale);
    const x=Math.round(128-(anchor-left)*w/width),y=365-Math.round((b.bottom-top)*h/height);
    assert.ok(x>=5&&x+w<=251&&y>=7&&y+h<=378,tree.id+' packing bounds');
    const cut=await sharp(data,{raw:{width:512,height:768,channels:4}}).extract({left,top,width,height}).resize(w,h,{kernel:'nearest'}).png().toBuffer();
    const cell=await sharp({create:{width:256,height:384,channels:4,background:'#00000000'}}).composite([{input:cut,left:x,top:y}]).png().toBuffer();
    const raw=await sharp(cell).raw().toBuffer();const packed=bounds(raw,256,384);
    assert.ok(packed.left>=7&&packed.right<=248&&packed.top>=7&&packed.bottom>=363&&packed.bottom<=367,tree.id+' clipped roots/crown');
    frames.push({...packed,hash:createHash('sha256').update(raw).digest('hex')});
    composite.push({input:cell,left:i%2*256,top:Math.floor(i/2)*384});
  }
  assert.equal(new Set(frames.map(f=>f.hash)).size,4,tree.id+' duplicate views');
  const pixelHeight=Math.max(...frames.map(f=>f.bottom-f.top+1));
  await sharp({create:{width:512,height:768,channels:4,background:'#00000000'}}).composite(composite).webp({lossless:true,effort:6}).toFile(path.join(staging,tree.id+'.webp'));
  catalog.push({...tree,pixelHeight,status:'perspective-4-5'});
  report.push({id:tree.id,source:source.path,frames});
}
// Validate the complete set before touching any runtime atlas.
for(const tree of catalog)await fs.copyFile(path.join(staging,tree.id+'.webp'),path.join('public/art/trees',tree.id+'.webp'));
await fs.writeFile('public/art/trees/manifest.json',JSON.stringify({trees:catalog},null,2)+'\n');
await fs.writeFile('src/game/tree-catalog.ts',`export interface TreeArt {id:string;name:string;height:number;pixelHeight:number;status:string}\n// Generated by scripts/import-tree-perspective.mjs. Four views, root pivot (128,353).\nexport const treeCatalog:TreeArt[]=${JSON.stringify(catalog,null,2)};\n`);
await fs.writeFile(path.join(root,'generation.json'),JSON.stringify(records,null,2)+'\n');
await fs.writeFile(path.join(root,'packing-report.json'),JSON.stringify(report,null,2)+'\n');
// First view per species, at runtime scale, for visual review (not new artwork).
const tiles=[];
for(let i=0;i<catalog.length;i++){
  const tree=catalog[i];const cut=await sharp(path.join(staging,tree.id+'.webp')).extract({left:0,top:0,width:256,height:384}).resize(154,230,{kernel:'nearest'}).png().toBuffer();
  tiles.push({input:cut,left:(i%8)*160+3,top:Math.floor(i/8)*260});
  const label=Buffer.from(`<svg width="160" height="30"><text x="80" y="18" text-anchor="middle" fill="#233831" font-size="11" font-family="Arial">${tree.id}</text></svg>`);
  tiles.push({input:label,left:(i%8)*160,top:Math.floor(i/8)*260+230});
}
await sharp({create:{width:1280,height:1300,channels:4,background:'#d9e7c6'}}).composite(tiles).png().toFile(path.join(root,'contact-sheet.png'));
console.log('40 trees / 160 distinct transparent frames packed, roots aligned, originals preserved.');
