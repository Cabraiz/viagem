/**
 * Lit windows (card NEW-20261029-ORQ-muitas-luzes): finds the windows painted on each building sheet (dark blobs of
 * window size on the opaque art, per view) and writes their centres as fractions of the cell to
 * src/client/render/luzes/janelas.ts. The game lights a hashed share of them; nothing is drawn by code.
 * Run: node scripts/luzes-janelas.mjs [--debug <dir>]  (debug: one PNG per sheet with the found windows boxed).
 */
import sharp from 'sharp';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';

const manifest=JSON.parse(readFileSync('public/art/manifest.json','utf8'));
const BUILDINGS=/^(boteco-apocaliptico|farmacia|padaria|escola|ubs|igreja-evangelica|acougue|borracharia|lan-house|loterica|salao-beleza|conjunto-habitacional|predio-apto-8a|predio-apto-5a|predinho-3a|igrejinha|casa-geminada|casa-laje-2x1|condominio-guarita|casa-laje-1x1|puxadinho)-\d+$/;
const dbg=process.argv.indexOf('--debug'),DEBUG=dbg>0?process.argv[dbg+1]:undefined;
if(DEBUG)mkdirSync(DEBUG,{recursive:true});

const pieces=Object.assign({},...Object.values(manifest.groups).filter(g=>g.output==='city/decor'||String(g.output).endsWith('city/decor')).map(g=>g.pieces));
const out={};
for(const [id,p] of Object.entries(pieces)){
  if(!BUILDINGS.test(id)||!p?.files?.sheet)continue;
  const file=`public/art/city/decor/${p.files.sheet.file}`;
  const {data,info}=await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const views=p.files.sheet.views??4,W=info.width/views,H=info.height;
  out[id]=[];
  const boxes=[];
  for(let v=0;v<views;v++){
    const found=windows(data,info.width,v*W,W,H);
    out[id].push(found.map(b=>[+(((b.x0+b.x1)/2)/W).toFixed(3),+(((b.y0+b.y1)/2)/H).toFixed(3),+((b.x1-b.x0)/W).toFixed(3),+((b.y1-b.y0)/H).toFixed(3)]));
    boxes.push(...found.map(b=>({...b,x0:b.x0+v*W,x1:b.x1+v*W})));
  }
  if(DEBUG){
    const svg=`<svg width="${info.width}" height="${H}" xmlns="http://www.w3.org/2000/svg">${boxes.map(b=>`<rect x="${b.x0}" y="${b.y0}" width="${b.x1-b.x0}" height="${b.y1-b.y0}" fill="none" stroke="#ff0" stroke-width="2"/>`).join('')}</svg>`;
    await sharp(file).flatten({background:'#777'}).composite([{input:Buffer.from(svg)}]).toFile(`${DEBUG}/${id}.png`);
  }
}
writeFileSync('src/client/render/luzes/janelas.ts',`/** Generated by scripts/luzes-janelas.mjs: per building id, per view, its painted windows [x, y, w, h] (fractions of the cell). */
export const JANELAS:Readonly<Record<string,readonly (readonly (readonly [number,number,number,number])[])[]>>=${JSON.stringify(out)};
`);
console.log(Object.keys(out).length,'buildings,',Object.values(out).flat(2).length,'windows');

/** Dark window-sized blobs of one frame (x0..x0+W), from a 2× downsampled luminance mask closed by one px. */
function windows(px,stride,x0,W,H){
  const S=2,w=Math.floor(W/S),h=Math.floor(H/S),lum=new Float32Array(w*h),opaque=new Uint8Array(w*h);
  const vals=[];
  for(let y=0;y<h;y++)for(let x=0;x<w;x++){
    let l=0,a=255;
    for(let dy=0;dy<S;dy++)for(let dx=0;dx<S;dx++){const i=((y*S+dy)*stride+x0+x*S+dx)*4;l+=.299*px[i]+.587*px[i+1]+.114*px[i+2];a=Math.min(a,px[i+3]);}
    lum[y*w+x]=l/(S*S);opaque[y*w+x]=a>200?1:0;if(a>200)vals.push(l/(S*S));
  }
  vals.sort((a,b)=>a-b);
  const median=vals[vals.length>>1]??128,dark=new Uint8Array(w*h);
  for(let i=0;i<w*h;i++)dark[i]=opaque[i]&&lum[i]<median*.5?1:0;
  // Close: bars and frames split a window; one px of dilation joins them back.
  const m=new Uint8Array(w*h);
  for(let y=1;y<h-1;y++)for(let x=1;x<w-1;x++){let any=0;for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++)any|=dark[(y+dy)*w+x+dx];m[y*w+x]=any;}
  const seen=new Uint8Array(w*h),res=[],stack=[];
  for(let s=0;s<w*h;s++){
    if(!m[s]||seen[s])continue;
    let n=0,bx0=w,by0=h,bx1=0,by1=0;stack.push(s);seen[s]=1;
    while(stack.length){
      const i=stack.pop(),x=i%w,y=(i/w)|0;n++;
      bx0=Math.min(bx0,x);by0=Math.min(by0,y);bx1=Math.max(bx1,x);by1=Math.max(by1,y);
      for(const j of [i-1,i+1,i-w,i+w])if(j>=0&&j<w*h&&m[j]&&!seen[j]){seen[j]=1;stack.push(j);}
    }
    const bw=(bx1-bx0+1)*S,bh=(by1-by0+1)*S,fill=n*S*S/(bw*bh);
    // Window size: 12 px up to 16 % of the cell width, upright or square (roof and ground shadows lie flat), mostly
    // filled, and on the walls (not the roof band at the top nor the ground at the feet).
    const cy=(by0+by1+1)*S/2;
    if(bw<12||bh<12||bw>W*.16||bh>W*.17||bh<bw*.7||bh>bw*2.6||fill<.35||cy<H*.1||cy>H*.93)continue;
    // Roof and ground shadows sit on snow: the ring around a window is wall, not much brighter than the art's median.
    let ring=0,rn=0;
    for(let y=Math.max(0,by0-3);y<=Math.min(h-1,by1+3);y++)for(let x=Math.max(0,bx0-3);x<=Math.min(w-1,bx1+3);x++){
      if(x>=bx0-1&&x<=bx1+1&&y>=by0-1&&y<=by1+1)continue;
      if(opaque[y*w+x]){ring+=lum[y*w+x];rn++;}
    }
    if(!rn||ring/rn>median*1.3)continue;
    res.push({x0:bx0*S,y0:by0*S,x1:(bx1+1)*S,y1:(by1+1)*S});
  }
  return res;
}
