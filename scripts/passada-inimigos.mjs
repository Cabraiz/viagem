#!/usr/bin/env node
/**
 * Card NEW-20261022-ORQ-monstros-sem-deslizar: the drawn stride of every enemy walk sheet (public/art/enemies), the
 * same method as scripts/passada.mjs (the hero's): on the side rows (W = row 2, E = row 6 of the 8-direction sheets:
 * the travel lies across the screen, no foreshortening), frames i and i+1 are matched in the feet band (the lowest
 * ~14 % of the figure); the shift that best lays one on the other, among the shifts going back (the planted foot stays
 * on the ground while the body goes on), is the foot's travel in that step. The sum over the cycle, over the figure's
 * height, is the stride in heights per cycle.
 *
 *   node scripts/passada-inimigos.mjs            # table per enemy
 *   node scripts/passada-inimigos.mjs --json f   # also writes the table as JSON
 *   node scripts/passada-inimigos.mjs --ts       # writes src/client/art/enemy-strides.ts (the client's table)
 */
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sharp=createRequire(path.join(ROOT,'package.json'))('sharp');
const manifest=JSON.parse(fs.readFileSync(path.join(ROOT,'public/art/manifest.json'),'utf8'));
const group=manifest.groups.inimigos,pieces=group.pieces??group;
const ROWS={W:{row:2,ux:-1},E:{row:6,ux:1}};

/** Alpha masks (alpha > 128) of row `row`'s frames of a walk file. */
async function masks(file,row){
  const [cw,ch]=file.cell,n=file.frames,out=[];
  const cache=new Map();
  for(let i=0;i<n;i++){
    const g=row*n+i;const page=file.pages.find(p=>g>=p.firstFrame&&g<p.firstFrame+p.frameCount);const l=g-page.firstFrame;
    let img=cache.get(page.file);
    if(!img){img=await sharp(path.join(ROOT,group.output??'public/art/enemies',page.file)).ensureAlpha().raw().toBuffer({resolveWithObject:true});cache.set(page.file,img);}
    const c=l%page.columns,r=Math.floor(l/page.columns),a=new Uint8Array(cw*ch);
    for(let y=0;y<ch;y++)for(let x=0;x<cw;x++)a[y*cw+x]=img.data[((r*ch+y)*img.info.width+c*cw+x)*4+3]>128?1:0;
    out.push(a);
  }
  return out;
}
/** Stride of one side row: {travel px per cycle, height px, stride, fill (share of the feet band matched)}. */
async function rowStride(file,{row,ux}){
  const [cw,ch]=file.cell,n=file.frames,M=await masks(file,row);
  let bottom=0,topY=ch;
  for(const a of M){for(let j=a.length-1;j>=0;j--)if(a[j]){bottom=Math.max(bottom,Math.floor(j/cw));break;}for(let j=0;j<a.length;j++)if(a[j]){topY=Math.min(topY,Math.floor(j/cw));break;}}
  const height=bottom-topY+1,top=bottom-Math.max(4,Math.round(height*.14)),R=Math.max(4,Math.round(cw*.08));
  let travel=0,fill=0;
  for(let i=0;i<n;i++){
    const A=M[i],B=M[(i+1)%n];let best=-1,back=0,area=0;
    for(let y=top;y<=bottom;y++)for(let x=0;x<cw;x++)area+=A[y*cw+x];
    for(let sy=-3;sy<=3;sy++)for(let sx=-R;sx<=R;sx++){
      if(-sx*ux<0)continue;
      let s=0;for(let y=top;y<=bottom;y++)for(let x=0;x<cw;x++){if(!A[y*cw+x])continue;const X=x+sx,Y=y+sy;if(X>=0&&X<cw&&Y>=0&&Y<ch&&B[Y*cw+X])s++;}
      if(s>best||(s===best&&Math.abs(sx)<Math.abs(back))){best=s;back=-sx*ux;}
    }
    travel+=back;fill+=area?best/area:0;
  }
  return {travel,height,stride:travel/height,fill:fill/n};
}

const rows=[];
for(const [id,piece] of Object.entries(pieces)){
  const file=piece.files?.walk;if(!file)continue;
  const W=await rowStride(file,ROWS.W),E=await rowStride(file,ROWS.E);
  rows.push({id,frames:file.frames,fps:file.fps,cell:file.cell[0],W,E,stride:(W.stride+E.stride)/2});
}
for(const r of rows)console.log(`${r.id.padEnd(28)} ${r.frames}f ${String(r.fps).padStart(2)}fps cell ${String(r.cell).padStart(3)}  W ${r.W.travel.toFixed(0).padStart(3)}/${r.W.height} E ${r.E.travel.toFixed(0).padStart(3)}/${r.E.height}  stride ${r.stride.toFixed(2)}  fit ${((r.W.fill+r.E.fill)/2).toFixed(2)}`);
const s=rows.map(r=>r.stride).sort((a,b)=>a-b),mid=s.length>>1;
console.log(`median stride ${(s.length%2?s[mid]:(s[mid-1]+s[mid])/2).toFixed(2)} heights per cycle over ${s.length} walks`);
const j=process.argv.indexOf('--json');if(j>0)fs.writeFileSync(process.argv[j+1],JSON.stringify(rows,null,1));
if(process.argv.includes('--ts')){
  const body=rows.map(r=>`  '${r.id}':${+r.stride.toFixed(3)},`).join('\n');
  fs.writeFileSync(path.join(ROOT,'src/client/art/enemy-strides.ts'),`// Generated by scripts/passada-inimigos.mjs from public/art/manifest.json: do not edit by hand.
// Per enemy art id with a walk sheet, its drawn stride: how far the planted foot travels back in one walk cycle, in
// heights of the figure (the mean of the W and E rows). art/horde-art.ts walks the sheet by the ground covered with it.
export const ENEMY_STRIDES:Readonly<Record<string,number>>=Object.freeze({
${body}
});
`);
}
