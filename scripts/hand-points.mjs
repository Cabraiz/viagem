#!/usr/bin/env node
/**
 * Card NEW-20261021-ORQ-arma-na-mao-viciado: measures, offline, where the weapon hand is in every M16 pose of a class
 * (walk 16, attack 16, idle 8, run 16 when drawn, the 5 drawn directions; docs/movement16.md) and writes src/client/sprites/hand-points-data.ts.
 * The weapon hand is the one that punches in the attack sheet of that direction (the leading side): S screen-left,
 * N screen-right, and the facing side for W, NW and SE (the mirrored E, NE and SW reuse it flipped, so in the mirror
 * the weapon changes hands with the drawing).
 * Per pose: the skin pixels (alpha > 40, the class's skin tone) on that side of the body between the chin and the
 * knees; the hand is the outermost cluster. A frame the rule gets wrong is set by hand in OVERRIDES (96 px cell).
 * The table is keyed by the sheet's file name (it carries the sha12): a reimported sheet has no entry and the game
 * goes back to the weapon sticker at the hero's side (render/arsenal-fx.ts).
 *
 *   node scripts/hand-points.mjs --ids viciado-em-bet            # writes the table
 *   node scripts/hand-points.mjs --ids viciado-em-bet --sheet out # + one debug PNG per sheet (dot on the hand)
 */
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sharp=createRequire(path.join(ROOT,'package.json'))('sharp');
const MANIFEST=path.join(ROOT,'public/art/manifest.json');
const OUT=path.join(ROOT,'src/client/sprites/hand-points-data.ts');
const HEAD=`// Generated by scripts/hand-points.mjs (card NEW-20261021-ORQ-arma-na-mao-viciado): do not edit; fix a pose in its OVERRIDES.
import type {HandSheet} from './hand-points.ts';
export const HAND_POINTS:Readonly<Record<string,HandSheet>>=`;
const CELL=96;
/** Which side the weapon hand is on, per drawn direction (−1 screen-left, +1 screen-right). */
const SIDE={S:-1,N:1,W:-1,NW:-1,SE:1,E:1,NE:1,SW:-1};
/** Back-facing directions: the hand is in front of the hero, so the weapon goes behind the body. */
const BEHIND=new Set(['N','NW','NE']);
/**
 * Manual fixes, `<id>:<motion>16-<DIR>` → {frame: [x, y]} in the 96 px cell; a third element 1 puts the weapon behind
 * the body in that pose (the hand is hidden behind it).
 * viciado W: the weapon hand is the far one; while walking it swings behind the body for frames 1-3 and 8 (the rule
 * then finds the near hand: in between its neighbours instead), and at rest it hangs hidden (the rule finds the nose).
 */
const hidden=(a,b,t)=>[Math.round((a[0]+(b[0]-a[0])*t)*10)/10,Math.round((a[1]+(b[1]-a[1])*t)*10)/10,1];
const OVERRIDES={
  'viciado-em-bet:walk16-W':{1:hidden([44.7,49.4],[46.6,42.4],.25),2:hidden([44.7,49.4],[46.6,42.4],.5),3:hidden([44.7,49.4],[46.6,42.4],.75),
    8:hidden([43.7,42.5],[42.9,47.9],.5)},
  'viciado-em-bet:idle16-W':Object.fromEntries(Array.from({length:8},(_,i)=>[i,[46,56,1]])),
};

const args=process.argv.slice(2);
const arg=name=>{const i=args.indexOf(name);return i>=0?args[i+1]:undefined;};
const ids=(arg('--ids')??'viciado-em-bet').split(',');
const sheetDir=arg('--sheet');

const skin=(r,g,b,a)=>a>40&&r>150&&g>90&&g<205&&b<140&&r-b>70&&r>g;

/** The hand of one pose: outermost skin cluster on `side`, between the chin (the top for a back view: no face) and the knees. */
export function handOf(px,side,back=false){
  let top=CELL,bot=-1;
  for(let y=0;y<CELL;y++)for(let x=0;x<CELL;x++)if(px.alpha(x,y)>40){top=Math.min(top,y);bot=Math.max(bot,y);}
  if(bot<0)return undefined;
  const h=bot-top,y0=Math.round(top+(back?0:h*.22)),y1=Math.round(bot-h*.27);
  let best;
  for(let y=y0;y<=y1;y++)for(let x=0;x<CELL;x++){
    if(!px.skin(x,y))continue;
    const v=side*x;if(!best||v>best.v)best={v,x,y};
  }
  if(!best)return undefined;
  // The cluster: skin within 5 px inward of the outermost column and 5 px of its row.
  let sx=0,sy=0,n=0;
  for(let y=Math.max(y0,best.y-5);y<=Math.min(y1,best.y+5);y++)for(let x=0;x<CELL;x++){
    if(!px.skin(x,y))continue;
    const d=side*(best.x-x);if(d<0||d>5)continue;
    sx+=x;sy+=y;n++;
  }
  return [Math.round(sx/n*10)/10,Math.round(sy/n*10)/10];
}

async function measure(file,dir){
  const {data,info}=await sharp(file).raw().ensureAlpha().toBuffer({resolveWithObject:true});
  const cols=info.width/CELL,rows=info.height/CELL,points=[];
  for(let c=0;c<cols*rows;c++){
    const ox=(c%cols)*CELL,oy=Math.floor(c/cols)*CELL;
    const at=(x,y)=>((oy+y)*info.width+ox+x)*4;
    const px={alpha:(x,y)=>data[at(x,y)+3],skin:(x,y)=>{const i=at(x,y);return skin(data[i],data[i+1],data[i+2],data[i+3]);}};
    points.push(handOf(px,SIDE[dir],BEHIND.has(dir)));
  }
  return points;
}

async function debugSheet(file,points,out){
  const meta=await sharp(file).metadata(),K=4;
  let svg=`<svg width="${meta.width*K}" height="${meta.height*K}" xmlns="http://www.w3.org/2000/svg">`;
  const cols=meta.width/CELL;
  points.forEach((p,i)=>{
    const ox=(i%cols)*CELL,oy=Math.floor(i/cols)*CELL;
    svg+=`<text x="${ox*K+4}" y="${oy*K+18}" font-size="16" font-family="Arial" fill="#c00">${i}</text>`;
    if(p)svg+=`<circle cx="${(ox+p[0])*K}" cy="${(oy+p[1])*K}" r="5" fill="none" stroke="#f00" stroke-width="2"/>`;
  });
  svg+='</svg>';
  await sharp(file).resize(meta.width*K,meta.height*K,{kernel:'nearest'}).flatten({background:'#bfe8c8'})
    .composite([{input:Buffer.from(svg),left:0,top:0}]).png().toFile(out);
}

const manifest=JSON.parse(fs.readFileSync(MANIFEST,'utf8'));
const table=fs.existsSync(OUT)?JSON.parse(fs.readFileSync(OUT,'utf8').slice(HEAD.length).replace(/;\s*$/,'')):{};
for(const id of ids){
  const files=manifest.groups.personagens.pieces[id]?.files??{};
  for(const key of Object.keys(table))if(key.startsWith(`${id}.`))delete table[key];
  for(const [name,f] of Object.entries(files)){
    const m=/^(walk|attack|idle|run)16-(\w+)$/.exec(name);if(!m)continue;
    const dir=m[2],src=path.join(ROOT,'public/art/sprites',f.file);
    const points=await measure(src,dir),fix=OVERRIDES[`${id}:${name}`]??{};
    for(const [i,p] of Object.entries(fix))points[Number(i)]=p;
    if(points.some(p=>!p))throw new Error(`${f.file}: no hand in frame ${points.findIndex(p=>!p)}`);
    table[f.file]={side:SIDE[dir],behind:BEHIND.has(dir),points};
    if(sheetDir){fs.mkdirSync(sheetDir,{recursive:true});await debugSheet(src,points,path.join(sheetDir,`${id}.${name}.png`));}
    console.log(f.file,points.length);
  }
}
const sorted=Object.fromEntries(Object.keys(table).sort().map(k=>[k,table[k]]));
fs.writeFileSync(OUT,HEAD+JSON.stringify(sorted,null,0).replace(/\},"/g,'},\n"')+';\n');
console.log('wrote',path.relative(ROOT,OUT));
